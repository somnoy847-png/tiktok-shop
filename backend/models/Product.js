const mongoose = require("mongoose");


// =====================================================
// PRODUCT SCHEMA
// =====================================================

const productSchema = new mongoose.Schema(
    {

        // =================================================
        // PRODUCT IMAGE
        // =================================================

        image: {
            type: String,
            required: true,
            trim: true
        },


        // =================================================
        // PRODUCT NAME
        // =================================================

        name: {
            type: String,
            required: true,
            trim: true
        },


        // =================================================
        // SKU
        // =================================================

        sku: {
            type: String,
            default: "",
            trim: true
        },


        // =================================================
        // DESCRIPTION
        // =================================================

        description: {
            type: String,
            default: "",
            trim: true
        },


        // =================================================
        // PRODUCT PRICE
        // Price displayed as the main product price
        // =================================================

        productPrice: {
            type: Number,
            default: 0,
            min: 0
        },


        // =================================================
        // COST PRICE
        // =================================================

        costPrice: {
            type: Number,
            required: true,
            min: 0
        },


        // =================================================
        // SALE PRICE
        // =================================================

        salePrice: {
            type: Number,
            required: true,
            min: 0
        },


        // =================================================
        // PROFIT
        // =================================================

        profit: {
            type: Number,
            required: true,
            min: 0
        },


        // =================================================
        // CATEGORY
        // =================================================

        category: {
            type: String,
            required: true,
            trim: true
        },


        // =================================================
        // STOCK
        // =================================================

        stock: {
            type: Number,
            default: 0,
            min: 0
        },


        // =================================================
        // STATUS
        // =================================================

        status: {
            type: String,
            enum: [
                "active",
                "inactive"
            ],
            default: "active"
        }

    },

    {
        timestamps: true
    }

);


// =====================================================
// MODEL
// =====================================================

const Product =
    mongoose.model(
        "Product",
        productSchema
    );


// =====================================================
// EXPORT
// =====================================================

module.exports =
    Product;